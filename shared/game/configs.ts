export const DAILY_CONFIGS = definitions.map((definition) => validateGameConfig(definition));

export function getDailyConfig(index: number): DailyGameConfig {
  const normalized = ((index % DAILY_CONFIGS.length) + DAILY_CONFIGS.length) % DAILY_CONFIGS.length;
  const config = DAILY_CONFIGS[normalized];
  if (!config) throw new Error('No daily configuration is available.');
  return config;
}
